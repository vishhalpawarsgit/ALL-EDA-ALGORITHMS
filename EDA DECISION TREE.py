## Encoding

### Save the encodings

gender_encoding = LabelEncoder()
df['Gender'] = gender_encoding.fit_transform(df['Gender'])

bp_encoding = LabelEncoder()
df['BP'] = bp_encoding.fit_transform(df['BP'])

ch_encoding = LabelEncoder()
df['Cholesterol'] = ch_encoding.fit_transform(df['Cholesterol'])

drug_encoding = LabelEncoder()
df['Drug'] = drug_encoding.fit_transform(df['Drug'])

