import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import LabelEncoder
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

"""Load Data set first"""

df=pd.read_csv('/content/Humans dataset.csv')

"""EDA steps"""

df.shape

df.head()

df.describe().T

df.info()

#check null values. here no null values found in data set
df.isnull().sum()

#Identify duplicate records
df.duplicated().sum()

#remove duplicate records

df=df.drop_duplicates()

df

#Hadnlong  error values with NaN (column workclass,occupation having '?')
df.replace(["?", "@", "NA"], np.nan, inplace=True)

df.isnull().sum()

#handling NAN values with mode impute  for columns workclass,occupation(categorical col)
df["workclass"].fillna(df["workclass"].mode()[0], inplace=True)
df["occupation"].fillna(df['occupation'].mode()[0],inplace=True)

df

#Split the dataset into categorical and numerical columns
cat=df.select_dtypes(include='object')
num=df.select_dtypes(include='number')

## Outlier detection

def cap_outlier(series):
  Q1 = series.quantile(0.25)
  Q3 = series.quantile(0.75)
  IQR = Q3 - Q1

  UB = Q3 + (1.5 * IQR)
  LB = Q1 - (1.5 * IQR)

  return series.clip(LB, UB)

for col in num:
  df[col] = cap_outlier(df[col])

print('Outliers capped')
df.describe().T

# convert categorial columns in numerical value

le = LabelEncoder()


categorical_columns = ['workclass','education','marital.status','occupation','relationship','race','gender','native.country','income']

for col in categorical_columns:
    df[col] = le.fit_transform(df[col])

df

x=df.drop('income',axis=1)
y=df['income']

# Create Gaussian Naive Bayes model
model = GaussianNB()

#split data set into
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.2)

#train model
model.fit(x_train,y_train)

#make prediction

y_pred = model.predict(x_test)

#evaluate model
print("Accuracy:", accuracy_score(y_test, y_pred))
print("\nClassification Report:\n", classification_report(y_test, y_pred))
print("\nConfusion Matrix:\n", confusion_matrix(y_test, y_pred))

