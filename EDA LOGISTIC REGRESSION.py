## Import necessary libraries

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import LabelEncoder

from sklearn.metrics import confusion_matrix, accuracy_score, precision_score, recall_score, f1_score

## Load the dataset

df = pd.read_csv('/content/Titanic train dataset.csv')

df

"""### EDA"""

df.shape

df.info()

df.describe().T

## Drop unnecessary columns

df.drop(["PassengerId", "Name", "Ticket"], axis=1, inplace=True)

df

## Handling null values

df.isnull().sum()

## Cabin contains too many missing values

df.drop("Cabin", axis=1, inplace=True)

## Replace null values in age with mean

df['Age'].fillna(df['Age'].mean(), inplace=True)

df.isnull().sum()

## As the embarked column has only 2 rows as null, we will simply delete those rows where we find null values

df.dropna(inplace=True)

df.isnull().sum()

## Handling duplicate values

df.duplicated().sum()

## Remove the duplicates

df.drop_duplicates(inplace=True)

df.duplicated().sum()

df.shape

## Seperate categorical and numerical columns

cat = df.select_dtypes(include='object').columns
num = df.select_dtypes(exclude='object').columns

cat

num

## Handling outliers using IQR

for i in num:
  Q1 = df[i].quantile(0.25)
  Q3 = df[i].quantile(0.75)
  IQR = Q3 - Q1

  LB = Q1 - (1.5 * IQR)
  UB = Q3 + (1.5 * IQR)

  df[i] = np.where(df[i] < LB, LB, df[i])
  df[i] = np.where(df[i] > UB, UB, df[i])

df.shape

## Convert categorical variables to numerical

le = LabelEncoder()
for i in cat:
  df[i] = le.fit_transform(df[i])

df

## Univariate analysis

df.hist(figsize=(10,10))
plt.show()

## correlation matrix

sns.heatmap(df.corr(), annot = True, cmap = 'coolwarm')
plt.show()

"""### Model building"""

X = df.drop('Survived', axis=1)
y = df['Survived']

X

y

## Divide the dataset into train-test

X_train, X_test, y_train, y_test = train_test_split(X, y, train_size =0.7)

model = LogisticRegression()

## Building the model

model.fit(X_train, y_train)

y_pred = model.predict(X_test)

## Model evaluation


cm = confusion_matrix(y_test, y_pred)
print(cm)

acc = accuracy_score(y_test, y_pred)
print(acc)

precison = precision_score(y_test, y_pred)
print(precison)

recall = recall_score(y_test, y_pred)
print(recall)

f1s = f1_score(y_test, y_pred)
print(f1s)

"""Model building is done with 75% accuracy"""

